/**
 * @file        call_event_task_manage_internal.h
 * @brief       通话事件 & 空闲任务管理模块（内部使用）
 * @details     事件注册、分发、空闲任务调度管理
 * @ingroup     call_event
 */

#ifndef __CALL_EVENT_TASK_MANAGE_INTERNAL_H__
#define __CALL_EVENT_TASK_MANAGE_INTERNAL_H__

#include "call_core.h"

/**
 * @brief 空闲任务类型枚举（与普通事件区分）
 */
typedef enum
{
  IDLE_TASK_HEARTBEAT = 0, /**< 心跳任务 */
  IDLE_TASK_MAX            /**< 空闲任务类型上限 */
} call_idle_task_type_t;

/**
 * @brief 事件回调函数类型
 */
typedef int (*call_event_handler_t)(device_info_attr *info_attr);

/**
 * @brief 空闲任务回调函数类型
 */
typedef int (*call_idle_task_handler_t)(void);

/*********************************************************************
 * 功能描述: 注册事件处理器（业务模块绑定事件类型与处理函数）
 * 输入参数: event_type - 事件类型ID（对应 CALL_EVENT_ID_xxx 定义）
 *          handler - 事件处理函数指针（符合 call_event_handler_t 类型）
 * 返回值:   int - 0=注册成功，-1=注册失败（参数无效/重复注册）
 * 注意事项: 需在模块初始化阶段调用，确保事件分发前完成注册
 ********************************************************************/
int call_event_handler_register(int event_type, call_event_handler_t handler);

/*********************************************************************
 * 功能描述: 注销事件处理器（业务模块解除事件类型与处理函数的绑定）
 * 输入参数: event_type - 事件类型ID（对应 CALL_EVENT_ID_xxx 定义）
 * 返回值:   int - 0=注销成功，-1=注销失败（参数无效/未注册）
 * 注意事项: 需在模块反初始化阶段调用，避免资源泄漏
 ********************************************************************/
int call_event_handler_unregister(int event_type);

/*********************************************************************
 * 功能描述: 分发事件（触发事件对应的业务处理函数）
 * 输入参数: event_attr - 事件属性结构体指针（包含事件类型、设备信息等，不可为NULL）
 * 返回值:   int - 0=分发成功（业务处理成功），-1=分发失败（参数无效/无对应处理器）
 * 注意事项: 事件发生时调用，自动匹配注册的处理函数并执行
 ********************************************************************/
int call_event_dispatch(call_cb_attr *event_attr);

/*********************************************************************
 * 功能描述: 注册空闲任务处理器（业务模块绑定空闲任务与处理函数）
 * 输入参数: task_id - 空闲任务ID（0~7，可通过宏调整上限）
 *          handler - 空闲任务处理函数指针（符合 call_idle_task_handler_t 类型）
 * 返回值:   int - 0=注册成功，-1=注册失败（参数无效/重复注册）
 * 注意事项: 需在模块初始化阶段调用，确保事件线程启动前完成注册
 ********************************************************************/
int call_idle_task_handler_register(int task_id, call_idle_task_handler_t handler);

/*********************************************************************
 * 功能描述: 注销空闲任务处理器（业务模块解除空闲任务与处理函数的绑定）
 * 输入参数: task_id - 空闲任务ID（0~7，可通过宏调整上限）
 * 返回值:   int - 0=注销成功，-1=注销失败（参数无效/未注册）
 * 注意事项: 需在模块反初始化阶段调用，避免资源泄漏
 ********************************************************************/
int call_idle_task_handler_unregister(int task_id);

/*********************************************************************
 * 新增：空闲任务迭代
 * 返回：无
 * 注意事项: 由事件线程在无普通事件处理时调用，优先级低于普通事件
 ********************************************************************/
void call_idle_task_iterate(void);

#endif // __CALL_EVENT_TASK_MANAGE_INTERNAL_H__